//3.1.Что в имени твоем ? (5)
//В алфавите племени мумба - юмба только три буквы, которые обозначаются как A, B и D.
//Юношам в день совершеннолетия принято давать взрослые имена, состоящие ровно из N букв(1 ≤ N ≤ 35).
//Повторение букв в имени не ограничивается.
//Если юноша не может представить вождю скальп врага, то в имени присутствует подстрока BAD(возможно, в нескольких экземплярах), иначе такие имена категорически запрещаются.
//Сколько разных имен может быть в племени мумба - юмба для юношей, запоздавших в развитии(не представивших скальп) ?
//Ввод
//Единственная строка содержит целое положительное число N.
//Вывод
//Выводится единственное число - количество имен длины N, содержащих подстроку BAD.
//Трофимов Ярослав ПС-24
//Visual Studio 2022

#include <iostream>
#include <fstream>
#include <vector>
using namespace std;

int main() {
    ifstream fin("input.txt");
    ofstream fout("OUTPUT.TXT");

    int N;
    fin >> N;

    vector<vector<long long>> dp(N + 1, vector<long long>(3, 0));

    dp[0][0] = 1;

    for (int i = 1; i <= N; i++) {
        dp[i][0] = dp[i - 1][0] * 2 + dp[i - 1][1] + dp[i - 1][2];
        dp[i][1] = dp[i - 1][0] + dp[i - 1][1] + dp[i - 1][2];
        dp[i][2] = dp[i - 1][1];
    }

    long long total = 1;
    for (int i = 0; i < N; i++) {
        total *= 3;
    }

    long long no_bad = dp[N][0] + dp[N][1] + dp[N][2];

    long long result = total - no_bad;

    fout << result;

    fin.close();
    fout.close();

    return 0;
}